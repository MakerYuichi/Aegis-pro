"""
Build an sdist in a sandboxed container and return the wheel.

The container has:
  --network none          no network, ever
  --read-only             root filesystem is read-only
  --cap-drop ALL          no capabilities
  --no-new-privileges     no privilege escalation
  --pids-limit 64         bounded process tree
  --user <uid>:<gid>      non-root, matches the host user
  -v sdist:/build/source.tar.gz:ro
  -v wheelhouse:/wheelhouse:ro
  -v outdir:/build/out    read-write, fresh per run

Every docker run argument is either hardcoded, from config, or
generated. Nothing from the sdist flows into argv.
"""
from __future__ import annotations

import asyncio
import hashlib
import os
import shutil
import subprocess
import time
import uuid
import zipfile
from dataclasses import dataclass
from pathlib import Path

from loguru import logger

from src.config import settings


# Filename pattern for a wheel. Enforced on every file in the
# output directory before anything is copied.
_WHEEL_NAME_RE = r"^[A-Za-z0-9_.+-]+\.whl$"


class BuildError(Exception):
    """Infrastructure or validation failure. Never a resolution
    failure — those don't reach this module."""

    def __init__(self, reason: str, detail: str = ""):
        self.reason = reason
        self.detail = detail
        super().__init__(f"{reason}: {detail}" if detail else reason)


@dataclass(frozen=True)
class BuildOutput:
    """
    A validated, copied wheel from the build container.
    """
    wheel_path: Path
    wheel_sha256: str
    wheel_size_bytes: int


async def build_sdist(
    *,
    sdist_path: Path,
    wheelhouse_dir: Path,
    entrypoint_host_path: Path,
    workdir_host_path: Path,
    workdir_container_path: Path,
    timeout_seconds: int | None = None,
) -> BuildOutput:
    """
    Run the build container and return the validated wheel.

    Arguments
    ---------
    sdist_path
        Host-side path to the sdist tarball. Read-only mount.

    wheelhouse_dir
        Host-side path to the directory of build-requirement
        wheels. Read-only mount.

    entrypoint_host_path
        Host-side path to build_entrypoint.py. Read-only mount.

    workdir_host_path
        Host-side path to a fresh directory where the container's
        output is staged. The orchestrator creates and removes
        this; it's not in the persistent mirror.

    timeout_seconds
        Wall-clock limit. On timeout, the container is killed by
        name, not just the client process.
    """
    timeout = timeout_seconds or settings.BUILD_CONTAINER_TIMEOUT_SECONDS
    run_id = uuid.uuid4().hex[:12]
    container_name = f"aegis-build-{run_id}"

    out_dir_host = workdir_host_path / "out"
    out_dir_container = workdir_container_path / "out"

    argv = _build_argv(
        container_name=container_name,
        sdist_host=sdist_path,
        wheelhouse_host=wheelhouse_dir,
        entrypoint_host=entrypoint_host_path,
        out_host=out_dir_host,
    )
    logger.info(f"build_sdist argv: {argv}")

    start = time.monotonic()
    proc = await asyncio.create_subprocess_exec(
        *argv,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
    )

    try:
        stdout_bytes, _ = await asyncio.wait_for(
            proc.communicate(), timeout=timeout,
        )
    except asyncio.TimeoutError:
        await _kill_container(container_name)
        try:
            await proc.wait()
        except Exception:
            pass
        raise BuildError(
            "build_timeout", f"exceeded {timeout}s",
        )

    duration_ms = int((time.monotonic() - start) * 1000)
    stdout = stdout_bytes.decode("utf-8", errors="replace")

    if proc.returncode != 0:
        tail = stdout[-3000:] if len(stdout) > 3000 else stdout
        raise BuildError(
            "build_failed",
            f"exit={proc.returncode} duration={duration_ms}ms "
            f"tail={tail!r}",
        )

    wheel = _validate_and_copy_output(out_dir_container, workdir_container_path)

    logger.info(
        f"build_sdist: {wheel.wheel_path.name} "
        f"({wheel.wheel_size_bytes} bytes, "
        f"sha256 {wheel.wheel_sha256[:16]}..., "
        f"{duration_ms}ms)"
    )
    return wheel


def _build_argv(
    *,
    container_name: str,
    sdist_host: Path,
    wheelhouse_host: Path,
    entrypoint_host: Path,
    out_host: Path,
) -> list[str]:
    """
    Build the docker run argv. Every argument is either hardcoded,
    from config, or generated by this function. Nothing from the
    sdist's content or the manifest flows into argv.
    """
    uid = os.getuid()
    gid = os.getgid()
    return [
        "docker", "run", "--rm",
        "--name", container_name,
        "--network", "none",
        "--read-only",
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--pids-limit", "64",
        "--tmpfs", "/tmp:rw,size=512m,mode=1777",
        "--user", f"{uid}:{gid}",
        "--memory", settings.BUILD_CONTAINER_MEMORY_LIMIT,
        "--cpus", settings.BUILD_CONTAINER_CPU_LIMIT,
        "-v", f"{sdist_host}:/build/source.tar.gz:ro",
        "-v", f"{wheelhouse_host}:/wheelhouse:ro",
        "-v", f"{entrypoint_host}:/opt/build_entrypoint.py:ro",
        "-v", f"{out_host}:/build/out:rw",
        settings.BUILD_CONTAINER_IMAGE,
        "python", "/opt/build_entrypoint.py",
    ]


async def _kill_container(name: str) -> None:
    """
    Kill a container by name. Called on timeout. The Docker CLI
    client that we spawned has already been SIGKILLed by proc.kill()
    in the timeout handler — but SIGKILL can't be forwarded through
    the client to the daemon, so the container keeps running unless
    we address it by name.

    Best-effort: if the container is already gone, the docker kill
    exits nonzero and we ignore it. The alternative — leaving a
    runaway container consuming a build's worth of CPU — is worse.
    """
    try:
        p = await asyncio.create_subprocess_exec(
            "docker", "kill", name,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        )
        await p.wait()
    except Exception as e:
        logger.warning(f"build_sdist: docker kill {name} failed: {e}")


def _validate_and_copy_output(
    out_dir: Path, workdir: Path,
) -> BuildOutput:
    """
    Enumerate the container's output directory, validate each
    entry, and copy the accepted wheel into a directory the
    orchestrator owns.

    The container's output directory is untrusted input. Build
    code wrote to it and could have left symlinks, FIFOs, oversized
    files, or multiple files. Every entry is checked against
    lstat (not stat, so symlinks are seen), size cap, and the
    wheel filename pattern. Files that pass are copied — never
    renamed, never moved — into workdir/validated/.
    """
    if not out_dir.is_dir():
        raise BuildError("output_dir_missing", str(out_dir))

    entries = list(out_dir.iterdir())
    if len(entries) != 1:
        raise BuildError(
            "output_wheel_count",
            f"expected 1 wheel, found {len(entries)}",
        )

    entry = entries[0]

    # lstat: see the entry as it is, don't follow a symlink.
    st = entry.lstat()
    import stat as _stat

    if not _stat.S_ISREG(st.st_mode):
        raise BuildError(
            "output_not_regular_file",
            f"{entry.name}: mode {oct(st.st_mode)}",
        )

    import re
    if not re.match(_WHEEL_NAME_RE, entry.name):
        raise BuildError(
            "output_bad_wheel_name", entry.name,
        )

    max_bytes = settings.BUILD_WHEEL_MAX_BYTES
    if st.st_size > max_bytes:
        raise BuildError(
            "output_too_large",
            f"{entry.name}: {st.st_size} > {max_bytes}",
        )

    validated_dir = workdir / "validated"
    validated_dir.mkdir(exist_ok=True)
    dst = validated_dir / entry.name

    # Copy the bytes, not the file object. Copying follows the
    # real file. That's fine here — we've already established
    # lstat sees a regular file, so entry is the file itself.
    with open(entry, "rb") as src, open(dst, "wb") as out:
        shutil.copyfileobj(src, out, length=64 * 1024)

    sha = "sha256:" + hashlib.sha256(dst.read_bytes()).hexdigest()
    return BuildOutput(
        wheel_path=dst,
        wheel_sha256=sha,
        wheel_size_bytes=dst.stat().st_size,
    )
